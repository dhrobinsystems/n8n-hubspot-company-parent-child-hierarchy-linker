#!/usr/bin/env node
'use strict';

/**
 * Single-source-of-truth workflow builder.
 *
 * Embeds the tested modules in src/*.js verbatim into n8n Code nodes and renders workflow.json.
 *
 *   npm run build:workflow            -> writes workflow.json
 *   npm run build:workflow -- --check -> exits 1 if workflow.json is out of sync with src/
 *
 * The output is deterministic (no timestamps, IDs derived from node names) so --check is stable.
 */

const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SRC_DIR = path.join(ROOT, 'src');
const WORKFLOW_PATH = path.join(ROOT, 'workflow.json');

const WORKFLOW_NAME = 'HubSpot Company Parent-Child Hierarchy Linker';
const WEBHOOK_PATH = 'hubspot-company-hierarchy';
const CREDENTIAL_PLACEHOLDER = 'REPLACE_WITH_N8N_CREDENTIAL_ID';

const MODULE_FILES = ['hubspot-signature.js', 'event-filter.js', 'hierarchy-linker.js'];

function readModule(file) {
  return fs.readFileSync(path.join(SRC_DIR, file), 'utf8');
}

/** Deterministic RFC 4122-shaped ID derived from a seed string. */
function stableId(seed) {
  const h = crypto.createHash('sha1').update('n8n-hubspot-hierarchy:' + seed).digest('hex');
  const variant = ((parseInt(h[16], 16) & 0x3) | 0x8).toString(16);
  return [h.slice(0, 8), h.slice(8, 12), '5' + h.slice(13, 16), variant + h.slice(17, 20), h.slice(20, 32)].join('-');
}

function moduleVarName(file) {
  return '__' + file.replace(/\.js$/, '').replace(/[^a-zA-Z0-9]/g, '_');
}

/**
 * Wrap a module's source so it runs inside an n8n Code node. The source is inserted verbatim
 * between the BEGIN/END markers; tests assert byte-for-byte equality with src/.
 */
function embedModule(file) {
  const source = readModule(file);
  return [
    '// ==== BEGIN EMBEDDED MODULE: src/' + file + ' (generated by scripts/build-workflow.js - do not edit here) ====',
    'const ' + moduleVarName(file) + ' = (function () {',
    '  const module = { exports: {} };',
    '  (function (module, exports, require) {',
    source.replace(/\s+$/, ''),
    '  })(module, module.exports, require);',
    '  return module.exports;',
    '})();',
    '// ==== END EMBEDDED MODULE: src/' + file + ' ====',
    '',
  ].join('\n');
}

const ENV_PRELUDE = [
  "const env = (typeof $env !== 'undefined' && $env) ? $env : {};",
  '',
].join('\n');

/* ------------------------------ Code node bodies ------------------------------ */

function verifySignatureCode() {
  return [
    embedModule('hubspot-signature.js'),
    ENV_PRELUDE,
    'const signature = ' + moduleVarName('hubspot-signature.js') + ';',
    'const item = $input.first();',
    'const headers = (item.json && item.json.headers) || {};',
    '',
    '// The raw body is required: HubSpot signs the exact bytes it sent.',
    "let rawBody = '';",
    'try {',
    "  const buffer = await this.helpers.getBinaryDataBuffer(0, 'data');",
    "  rawBody = buffer.toString('utf8');",
    '} catch (e) {',
    '  if (item.binary && item.binary.data && item.binary.data.data) {',
    "    rawBody = Buffer.from(item.binary.data.data, 'base64').toString('utf8');",
    '  } else if (item.json && item.json.body !== undefined) {',
    "    rawBody = typeof item.json.body === 'string' ? item.json.body : JSON.stringify(item.json.body);",
    '  }',
    '}',
    '',
    '// HubSpot signs the full public URL it called. Set WEBHOOK_PUBLIC_URL when n8n sits behind a proxy.',
    "let uri = env.WEBHOOK_PUBLIC_URL || (item.json && item.json.webhookUrl) || '';",
    'const query = (item.json && item.json.query) || {};',
    'const queryString = new URLSearchParams(query).toString();',
    "if (queryString && uri.indexOf('?') === -1) uri += '?' + queryString;",
    '',
    'const verification = signature.verifyHubSpotSignatureV3({',
    '  clientSecret: env.HUBSPOT_APP_CLIENT_SECRET,',
    "  method: 'POST',",
    '  uri,',
    '  rawBody,',
    '  headers,',
    '  maxAgeMs: Number(env.SIGNATURE_MAX_AGE_MS) > 0 ? Number(env.SIGNATURE_MAX_AGE_MS) : signature.DEFAULT_MAX_AGE_MS,',
    '});',
    '',
    'let events = [];',
    "let parseError = null;",
    'if (verification.valid) {',
    '  try {',
    '    events = JSON.parse(rawBody);',
    '    if (!Array.isArray(events)) events = [events];',
    '  } catch (e) {',
    "    parseError = 'INVALID_JSON_BODY';",
    '  }',
    '}',
    '',
    'return [{',
    '  json: {',
    '    valid: verification.valid && !parseError,',
    '    reason: parseError || verification.reason,',
    '    requestTimestamp: verification.timestamp,',
    '    eventCount: events.length,',
    '    events,',
    '  },',
    '}];',
  ].join('\n');
}

function filterEventsCode() {
  return [
    embedModule('event-filter.js'),
    ENV_PRELUDE,
    'const filter = ' + moduleVarName('event-filter.js') + ';',
    'const events = $input.first().json.events || [];',
    'const outcome = filter.filterWebhookBatch(events, {',
    '  expectedPortalId: env.EXPECTED_PORTAL_ID,',
    '  appId: env.HUBSPOT_APP_ID,',
    '  watchedProperties: env.WATCHED_PROPERTIES,',
    '  maxEventsPerBatch: env.MAX_EVENTS_PER_BATCH,',
    '});',
    '',
    '// One item per company. An empty result ends the execution quietly.',
    'return outcome.companies.map((work) => ({',
    '  json: { work, batchStats: outcome.stats, rejectedCount: outcome.rejected.length },',
    '}));',
  ].join('\n');
}

function linkHierarchyCode() {
  return [
    embedModule('hierarchy-linker.js'),
    ENV_PRELUDE,
    'const linker = ' + moduleVarName('hierarchy-linker.js') + ';',
    'const config = linker.loadConfig(env);',
    'const client = linker.createHubSpotClient({',
    '  httpRequest: linker.createN8nHttpRequest(this.helpers),',
    '  token: env.HUBSPOT_PRIVATE_APP_TOKEN,',
    '  baseUrl: config.apiBaseUrl,',
    '  associationTypes: config.associationTypes,',
    '  maxRetries: config.maxRetries,',
    '  properties: config.properties,',
    '});',
    '',
    'const workItems = $input.all().map((i) => i.json.work).filter(Boolean);',
    'const results = await linker.processBatch(workItems, { client, config });',
    'const timestamp = new Date().toISOString();',
    "const executionId = (typeof $execution !== 'undefined' && $execution) ? $execution.id : null;",
    '',
    'return results.map((result, index) => ({',
    '  json: {',
    '    action: result.action,',
    '    reason: result.reason,',
    '    dryRun: result.dryRun,',
    '    companyId: result.companyId,',
    '    auditEnabled: config.auditLogEnabled,',
    '    reviewEnabled: config.reviewQueueEnabled,',
    '    audit: linker.buildAuditPayload(result, { timestamp, executionId, triggers: workItems[index] ? workItems[index].propertyNames : null }),',
    '    review: linker.buildReviewTicket(result, { timestamp }),',
    '  },',
    '}));',
  ].join('\n');
}

function classifyErrorCode() {
  return [
    embedModule('hierarchy-linker.js'),
    ENV_PRELUDE,
    'const linker = ' + moduleVarName('hierarchy-linker.js') + ';',
    'const alertUrl = env.ERROR_ALERT_WEBHOOK_URL || env.AUDIT_LOG_WEBHOOK_URL || \'\';',
    'return $input.all().map((item) => ({',
    '  json: {',
    '    alertEnabled: Boolean(alertUrl) && !/^REPLACE_WITH_/.test(alertUrl),',
    '    alertUrl,',
    '    alert: linker.buildErrorAlert(item.json, { timestamp: new Date().toISOString() }),',
    '  },',
    '}));',
  ].join('\n');
}

/* ------------------------------ Node factories ------------------------------ */

function node(name, type, typeVersion, position, parameters, extra) {
  return Object.assign({ id: stableId('node:' + name), name, type, typeVersion, position, parameters }, extra || {});
}

function codeNode(name, position, jsCode, extra) {
  return node(name, 'n8n-nodes-base.code', 2, position, { mode: 'runOnceForAllItems', language: 'javaScript', jsCode }, extra);
}

function booleanIf(name, position, leftValue) {
  return node(name, 'n8n-nodes-base.if', 2, position, {
    conditions: {
      options: { caseSensitive: true, leftValue: '', typeValidation: 'loose' },
      conditions: [
        {
          id: stableId('condition:' + name),
          leftValue,
          rightValue: '',
          operator: { type: 'boolean', operation: 'true', singleValue: true },
        },
      ],
      combinator: 'and',
    },
    options: {},
  });
}

function httpPost(name, position, urlExpression, bodyExpression, credentialName) {
  return node(
    name,
    'n8n-nodes-base.httpRequest',
    4.2,
    position,
    {
      method: 'POST',
      url: urlExpression,
      authentication: 'genericCredentialType',
      genericAuthType: 'httpHeaderAuth',
      sendBody: true,
      specifyBody: 'json',
      jsonBody: bodyExpression,
      options: { timeout: 10000 },
    },
    {
      credentials: { httpHeaderAuth: { id: CREDENTIAL_PLACEHOLDER, name: credentialName } },
      retryOnFail: true,
      maxTries: 3,
      waitBetweenTries: 2000,
      onError: 'continueRegularOutput',
    }
  );
}

function respondNode(name, position, statusCode, body) {
  return node(name, 'n8n-nodes-base.respondToWebhook', 1.1, position, {
    respondWith: 'json',
    responseBody: body,
    options: { responseCode: statusCode },
  });
}

/* ------------------------------ Workflow ------------------------------ */

function buildWorkflow() {
  const N = {
    webhook: 'HubSpot Company Webhook',
    verify: 'Verify HubSpot Signature',
    valid: 'Signature Valid?',
    ack: 'Acknowledge 200',
    reject: 'Reject 401',
    filter: 'Filter & Deduplicate Events',
    link: 'Resolve, Guard & Link Hierarchy',
    needsReview: 'Needs Human Review?',
    review: 'Create Review Ticket',
    auditOn: 'Audit Log Enabled?',
    audit: 'Send Audit Log',
    errorTrigger: 'Error Trigger',
    classify: 'Classify Error',
    alertOn: 'Error Alert Enabled?',
    alert: 'Send Error Alert',
  };

  const nodes = [
    node(N.webhook, 'n8n-nodes-base.webhook', 2, [0, 300], {
      httpMethod: 'POST',
      path: WEBHOOK_PATH,
      responseMode: 'responseNode',
      options: { rawBody: true },
    }, { webhookId: stableId('webhook:' + WEBHOOK_PATH) }),
    codeNode(N.verify, [220, 300], verifySignatureCode()),
    booleanIf(N.valid, [440, 300], '={{ $json.valid }}'),
    respondNode(N.ack, [660, 200], 200, '={{ JSON.stringify({ received: true, events: $json.eventCount }) }}'),
    respondNode(N.reject, [660, 420], 401, '={{ JSON.stringify({ received: false, reason: $json.reason }) }}'),
    codeNode(N.filter, [880, 200], filterEventsCode()),
    codeNode(N.link, [1100, 200], linkHierarchyCode()),
    booleanIf(N.needsReview, [1320, 100], "={{ $json.action === 'review' && $json.reviewEnabled }}"),
    httpPost(N.review, [1540, 100], '={{ $env.REVIEW_QUEUE_WEBHOOK_URL }}', '={{ JSON.stringify($json.review) }}', 'Review Queue Webhook Auth'),
    booleanIf(N.auditOn, [1320, 300], '={{ $json.auditEnabled }}'),
    httpPost(N.audit, [1540, 300], '={{ $env.AUDIT_LOG_WEBHOOK_URL }}', '={{ JSON.stringify($json.audit) }}', 'Audit Log Webhook Auth'),
    node(N.errorTrigger, 'n8n-nodes-base.errorTrigger', 1, [0, 640], {}),
    codeNode(N.classify, [220, 640], classifyErrorCode()),
    booleanIf(N.alertOn, [440, 640], '={{ $json.alertEnabled }}'),
    httpPost(N.alert, [660, 640], '={{ $json.alertUrl }}', '={{ JSON.stringify($json.alert) }}', 'Audit Log Webhook Auth'),
  ];

  const main = (...targets) => ({ main: targets.map((list) => list.map((t) => ({ node: t, type: 'main', index: 0 }))) });

  const connections = {
    [N.webhook]: main([N.verify]),
    [N.verify]: main([N.valid]),
    [N.valid]: main([N.ack], [N.reject]),
    [N.ack]: main([N.filter]),
    [N.filter]: main([N.link]),
    [N.link]: main([N.needsReview, N.auditOn]),
    [N.needsReview]: main([N.review], []),
    [N.auditOn]: main([N.audit], []),
    [N.errorTrigger]: main([N.classify]),
    [N.classify]: main([N.alertOn]),
    [N.alertOn]: main([N.alert], []),
  };

  return {
    name: WORKFLOW_NAME,
    nodes,
    connections,
    active: false,
    settings: {
      executionOrder: 'v1',
      saveManualExecutions: true,
      callerPolicy: 'workflowsFromSameOwner',
      errorWorkflow: 'REPLACE_WITH_THIS_WORKFLOW_ID',
    },
    pinData: {},
    meta: { templateCredsSetupCompleted: false },
    tags: [],
  };
}

function renderWorkflow() {
  return JSON.stringify(buildWorkflow(), null, 2) + '\n';
}

function main(argv) {
  const check = argv.includes('--check');
  const rendered = renderWorkflow();
  if (check) {
    const current = fs.existsSync(WORKFLOW_PATH) ? fs.readFileSync(WORKFLOW_PATH, 'utf8') : '';
    if (current !== rendered) {
      process.stderr.write('workflow.json is out of sync with src/. Run: npm run build:workflow\n');
      return 1;
    }
    process.stdout.write('workflow.json is in sync with src/ (' + MODULE_FILES.length + ' modules embedded).\n');
    return 0;
  }
  fs.writeFileSync(WORKFLOW_PATH, rendered);
  process.stdout.write('Wrote ' + path.relative(ROOT, WORKFLOW_PATH) + '\n');
  return 0;
}

if (require.main === module) {
  process.exitCode = main(process.argv.slice(2));
}

module.exports = {
  MODULE_FILES,
  WORKFLOW_PATH,
  WEBHOOK_PATH,
  CREDENTIAL_PLACEHOLDER,
  stableId,
  moduleVarName,
  embedModule,
  buildWorkflow,
  renderWorkflow,
  main,
};
